#!/usr/bin/env node

/**
 * Extension Builder & Packager
 *
 * Build process:
 *   1. Reads src/client/serializer.js (the pure, testable DOM serializer engine)
 *   2. Reads src/client/client.js (the main bridge IIFE)
 *   3. Concatenates them — serializer functions are hoisted before the IIFE
 *   4. Writes to extension/client.bundle.js (the single-file extension artifact)
 *   5. Packages extension/ into markup-bridge-extension.zip
 *
 * Architectural note:
 *   serializer.js uses ES module `export` syntax for testability.
 *   The build strips those `export` keywords so the functions become
 *   global within the IIFE scope when concatenated.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const serializerSrc = path.join(rootDir, 'src', 'client', 'serializer.js');
const clientSrc = path.join(rootDir, 'src', 'client', 'client.js');
const extensionDir = path.join(rootDir, 'extension');
const extensionBundle = path.join(extensionDir, 'client.bundle.js');
const zipOut = path.join(rootDir, 'markup-bridge-extension.zip');

console.log('[Build] Packaging Markup Bridge Chrome Extension...');

// 1. Read source files
if (!fs.existsSync(clientSrc)) {
  console.error(`[Build] Error: Could not find ${clientSrc}`);
  process.exit(1);
}
if (!fs.existsSync(serializerSrc)) {
  console.error(`[Build] Error: Could not find ${serializerSrc}`);
  process.exit(1);
}

const serializerCode = fs.readFileSync(serializerSrc, 'utf8');
const clientCode = fs.readFileSync(clientSrc, 'utf8');

// 2. Strip ES module export syntax from serializer so it works in browser IIFE context
//    The functions become available in the enclosing scope.
const serializerBrowserCode = serializerCode
  // Remove `export function` -> `function`
  .replace(/^export\s+function\s+/gm, 'function ')
  // Remove `export async function` -> `async function`
  .replace(/^export\s+async\s+function\s+/gm, 'async function ')
  // Remove `export const` -> `const`
  .replace(/^export\s+const\s+/gm, 'const ')
  // Remove standalone `export { ... }` blocks entirely
  .replace(/^export\s+\{[^}]*\};?\s*$/gm, '');

// 3. Assemble the final bundle:
//    [serializer browser code] + newline separator + [client IIFE]
const bundleHeader = `/**
 * Markup Bridge — Client Bundle
 * Auto-generated by bin/build-extension.js. Do not edit this file directly.
 * Source files:
 *   - src/client/serializer.js  (DOM Serializer Engine)
 *   - src/client/client.js      (Bridge UI & Communication)
 */
`;

const bundleCode = [
  bundleHeader,
  '// === BEGIN: DOM SERIALIZER ENGINE (from src/client/serializer.js) ===',
  serializerBrowserCode,
  '// === END: DOM SERIALIZER ENGINE ===',
  '',
  '// === BEGIN: BRIDGE CLIENT (from src/client/client.js) ===',
  clientCode,
  '// === END: BRIDGE CLIENT ===',
].join('\n');

fs.writeFileSync(extensionBundle, bundleCode, 'utf8');
console.log(`[Build] Bundle assembled: client.bundle.js (${(fs.statSync(extensionBundle).size / 1024).toFixed(1)} KB)`);
console.log(`  - serializer.js: ${(Buffer.byteLength(serializerCode) / 1024).toFixed(1)} KB`);
console.log(`  - client.js:     ${(Buffer.byteLength(clientCode) / 1024).toFixed(1)} KB`);

// 4. Package into zip file for easy distribution
try {
  if (fs.existsSync(zipOut)) {
    fs.unlinkSync(zipOut);
  }
  execSync(`cd "${rootDir}" && zip -q -r "${zipOut}" extension/ -x "extension/.DS_Store"`, { stdio: 'inherit' });
  console.log(`[Build] Created distribution package: markup-bridge-extension.zip (${(fs.statSync(zipOut).size / 1024).toFixed(1)} KB)`);
} catch (err) {
  console.warn('[Build] Warning: Could not create zip archive:', err.message);
}

console.log('[Build] Extension build complete. Ready for Chrome Developer Mode or download.');
